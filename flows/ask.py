"""**한 칸씩 묻는 틀** — 등록·취소·삭제처럼 *상태를 바꾸는 일*에 쓴다 (2026-09-22 사장님 결정).

사장님: 「이건 등록 일때만 그런거고 등록/취소/삭제 혹은 자동화 등에 맞을거 같아」

찾기·현황·질문에는 쓰지 않는다 — 저건 **물을 것이 없다.** 한 번 답하면 끝이다.
바꾸는 일만 묻는다: 한 번 만들면 되돌리기 번거롭고(Slack 은 채널 삭제가 없다),
지우는 일은 아예 못 되돌린다.

**여기 있는 것은 글자와 순수 함수뿐이다.** `api` 를 여기서 부르지 않는다 — 부르면 각
흐름의 시험이 `api` 를 갈아 끼울 수가 없어서, 그 흐름을 아예 못 시험한다 (9/22 에 한 번
그런 자리를 고쳤다). 흐름마다 `_say` 를 몇 줄 두는 값이 그 위험보다 싸다.
"""

import re

CANCEL = ("취소", "그만", "안 할래", "안할래", "아니요", "아니야", "됐어")
# **「네」 하나만 딱 쓰지 않는다** (2026-09-22 사장님 실측: 「네! 그러자고」 로 등록이 안 됐다).
# 예전에는 목록과 **똑같아야** 통과였다 — 「네」 는 되고 「네! 그러자고」 는 고치자는 말로
# 떨어져서, 답을 했는데 되묻는 봇이 됐다. 이 저장소가 같은 모양으로 세 번 넘어졌다
# (프로젝트 이름 · 번호 앞말 · 이제 대꾸까지).
#
# **맨 앞의 한 낱말만 본다.** 뒤에 무슨 말이 붙어도 「네」 로 시작하면 「네」 다.
# 「그래**서** 뭐?」 는 「그래」 뒤에 「서」 가 붙어 있어 안 걸린다 — 낱말이 끝나는 자리를 본다.
# 긴 것을 먼저 적는다: 「그러자고」 가 「그러자」 보다 앞이어야 통째로 걸린다
_YES_WORDS = ("네네", "넵", "네", "예", "응", "웅", "ㅇㅇ", "ㅇㅋ", "오케이", "오키", "okay", "ok", "콜",
              "그러자고", "그러자", "그러죠", "그래요", "그래", "그렇게", "그걸로", "그거로",
              "이대로", "그대로", "좋아요", "좋아", "좋습니다", "좋네", "맞아요", "맞아", "맞습니다", "맞네",
              "진행", "올려", "만들어")
YES_HEAD = re.compile(r"^\s*(?:" + "|".join(map(re.escape, _YES_WORDS)) + r")(?=[\s!.~,?…]|$)", re.I)
YES = _YES_WORDS                       # 옛 이름 — 목록으로 쓰는 자리가 남아 있다
# 지금 못 정할 수도 있다 — **묻는 칸 때문에 갇히면 안 된다** (이 저장소가 두 번 겪은 일)
LATER = ("나중", "모르", "건너", "없어", "없음", "패스", "skip", "미정", "안 정", "아직")
# 묻는 자리에서도 **이미 뜻이 있는 말**은 답으로 받지 않는다 — 「현황」 이 프로젝트 이름이
# 되면 그 방은 그 이름으로 남는다. **딱 그 말일 때만** 막는다: 「현황판 개편」 은 진짜 이름일 수 있다
COMMANDS = ("현황", "목록", "도움말", "도움", "정리", "내 할 일", "회의", "캔버스", "상세", "순서")
# 머리말은 답이 아니다 — 「**아니** 결제개편이 이름이야」 의 「아니」 까지 이름이 됐다 (시험이 잡았다)
HEAD = r"^\s*(오케이|오키|okay|ok|그럼|그러면|일단|자|아니|아니야|응|네)[\s,.!~]+"


def yes(text):
    """맞다는 뜻인가 — **맨 앞 한 낱말**로 본다. 뒤에 무슨 말이 붙어도 된다."""
    return bool(YES_HEAD.match(text or ""))


def cancelled(text):
    return (text or "").strip() in CANCEL


def later(text):
    return any(x in (text or "") for x in LATER)


def command(text):
    return (text or "").strip() in COMMANDS
